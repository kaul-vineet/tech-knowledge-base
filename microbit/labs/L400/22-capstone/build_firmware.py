"""Build the capstone board program from earlier labs (no copy-paste): frame_auth.py (lab 19) +
lab 17's solution.py + the small patches in firmware_patches.json (each must match exactly once).

Run:  python build_firmware.py    -> build/classroom_node.py (flash it as main.py on every board;
on a real board also write the board's 16-byte key to the file system and set ROLE/DEV)
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LABS = HERE.parent.parent
OUT = HERE / "build" / "classroom_node.py"


def build():
    spec = json.loads((HERE / "firmware_patches.json").read_text(encoding="utf-8"))
    auth, node = [(LABS / p).read_text(encoding="utf-8") for p in spec["base"]]
    for old, new in spec["patches"]:
        if node.count(old) != 1:
            raise ValueError("patch does not match exactly once: %r" % old[:50])
        node = node.replace(old, new)
    head = "# GENERATED by labs/L400/22-capstone/build_firmware.py - edit the labs, not this file.\n"
    return head + auth + "\n\n" + node


if __name__ == "__main__":
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print("wrote", OUT.relative_to(HERE), len(OUT.read_text(encoding="utf-8").splitlines()), "lines")
