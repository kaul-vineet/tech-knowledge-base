"""Build content/L500.json from tools/l500_23.py ... l500_27.py.

Run:  python tools/build_l500_json.py        (numpy only)
Each theorem's `checkOutput` is produced by running its check (labs/L500/<lab>/theorems.py::<id>) now, so the JSON
always holds real output. Writes the file fresh (delete, then write). Verify with: python research/l500_checks.py
"""
import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOPIC = HERE.parent
sys.path.insert(0, str(HERE))

import l500_23  # noqa: E402
import l500_24  # noqa: E402
import l500_25  # noqa: E402
import l500_26  # noqa: E402
import l500_27  # noqa: E402

ENV = "Python 3.12.15, numpy 2.5.3"
KEYS = ("id", "number", "level", "title", "phase", "category", "description", "outcome", "estimatedTime", "prerequisites",
        "learningObjectives", "glossary", "theorems", "problemSet", "caseStudy", "readings", "rubric", "conceptNote",
        "conceptSummary", "sources", "seeAlso", "next", "platforms", "validation")


def load_theorems(lab_path):
    path = TOPIC / lab_path / "theorems.py"
    spec = importlib.util.spec_from_file_location(f"theorems_{path.parent.name.replace('-', '_')}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def check_output(check):
    lab_file, tid = check.split("::")
    module = load_theorems(str(Path(lab_file).parent))
    return "\n".join(module.run([tid]))


def validation(lesson):
    n = lesson["number"]
    if lesson.get("theorems"):
        lab = lesson["theorems"][0]["check"].split("::")[0].rsplit("/", 1)[0]
        return {
            "status": "validated-local",
            "how": f"Ran locally ({ENV}; no quantum SDK needed): `python theorems.py` in {lab} (its output is each theorem's "
                   f"checkOutput, regenerated by tools/build_l500_json.py) and `python -m unittest -v` (2 tests OK); "
                   f"`python research/l500_checks.py` re-runs every check, compares it with checkOutput and recomputes every "
                   f"problem-set number. Platforms: authored and run on Linux only; the code uses pathlib and numpy only.",
            "pendingCi": [f"{lab}: theorems.py + unittest on macos-latest and windows-latest (CI matrix, not yet run)"],
        }
    return {
        "status": "validated-local",
        "how": f"No lab code in lesson {n}. `python research/l500_checks.py` recomputes the numeric problem-set answers; every "
               f"source URL was retrieved on 2026-10-30 (research/L500-evidence.md).",
        "pendingCi": [],
    }


def build():
    lessons = []
    for module in (l500_23, l500_24, l500_25, l500_26, l500_27):
        lesson = dict(module.LESSON)
        if "theorems" in lesson:
            lesson["theorems"] = [{**t, "checkOutput": check_output(t["check"])} for t in lesson["theorems"]]
        lesson["platforms"] = {"mac": "expected", "windows": "expected"}
        lesson["validation"] = validation(lesson)
        lessons.append({k: lesson[k] for k in KEYS if k in lesson})
    return lessons


def main():
    out = TOPIC / "content" / "L500.json"
    lessons = build()
    if out.exists():
        out.unlink()
    out.write_text(json.dumps(lessons, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    for lesson in lessons:
        print(f"#{lesson['number']} {lesson['title']}: {len(lesson.get('theorems', []))} theorems, "
              f"{len(lesson['problemSet'])} problems")
    print(f"wrote {out.relative_to(TOPIC)}")


if __name__ == "__main__":
    main()
