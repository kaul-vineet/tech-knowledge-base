"""Ports: the hexagon's own interfaces. Named for what they are FOR, not for a technology."""
from typing import Protocol, runtime_checkable


@runtime_checkable
class ForStoringLoans(Protocol):
    """Driven port (the domain calls it). Adapters: memory, SQLite, ..."""

    def add(self, book_id: str, member_id: str): ...
    def get(self, loan_id: int): ...
    def active(self) -> list: ...
    def mark_returned(self, loan_id: int) -> None: ...


class ForManagingLoans(Protocol):
    """Driving port (adapters call it). Adapters: HTTP, CLI, tests."""

    def borrow(self, book_id: str, member_id: str): ...
    def give_back(self, loan_id: int): ...
    def get(self, loan_id: int): ...
