"""RFC 9162 (CT v2, obsoletes RFC 6962) section 2.1 Merkle tree: leaf = SHA-256(0x00 || d), node = SHA-256(0x01 ||
left || right), split at the largest power of two < n. Inclusion and consistency proofs are generated by the
recursive definitions (2.1.3.1, 2.1.4.1) and verified with the iterative algorithms (2.1.3.2, 2.1.4.2)."""
import hashlib


def H(b: bytes) -> bytes:
    return hashlib.sha256(b).digest()


def leaf_hash(d: bytes) -> bytes:
    return H(b"\x00" + d)


def node_hash(left: bytes, right: bytes) -> bytes:
    return H(b"\x01" + left + right)


def _k(n: int) -> int:
    k = 1
    while k * 2 < n:
        k *= 2
    return k  # largest power of two smaller than n


def mth(leaves: list) -> bytes:
    """Merkle Tree Hash over a list of entries (bytes)."""
    if not leaves:
        return H(b"")
    if len(leaves) == 1:
        return leaf_hash(leaves[0])
    k = _k(len(leaves))
    return node_hash(mth(leaves[:k]), mth(leaves[k:]))


def inclusion_proof(m: int, leaves: list) -> list:
    if len(leaves) <= 1:
        return []
    k = _k(len(leaves))
    if m < k:
        return inclusion_proof(m, leaves[:k]) + [mth(leaves[k:])]
    return inclusion_proof(m - k, leaves[k:]) + [mth(leaves[:k])]


def verify_inclusion(leaf: bytes, index: int, size: int, path: list, root: bytes) -> bool:
    if index >= size:
        return False
    fn, sn, r = index, size - 1, leaf_hash(leaf)
    for p in path:
        if sn == 0:
            return False
        if fn & 1 or fn == sn:
            r = node_hash(p, r)
            if not fn & 1:
                while fn and not fn & 1:
                    fn, sn = fn >> 1, sn >> 1
        else:
            r = node_hash(r, p)
        fn, sn = fn >> 1, sn >> 1
    return sn == 0 and r == root


def _subproof(m: int, leaves: list, complete: bool) -> list:
    n = len(leaves)
    if m == n:
        return [] if complete else [mth(leaves)]
    k = _k(n)
    if m <= k:
        return _subproof(m, leaves[:k], complete) + [mth(leaves[k:])]
    return _subproof(m - k, leaves[k:], False) + [mth(leaves[:k])]


def consistency_proof(m: int, leaves: list) -> list:
    return _subproof(m, leaves, True) if 0 < m < len(leaves) else []


def verify_consistency(first: int, second: int, first_hash: bytes, second_hash: bytes, path: list) -> bool:
    if first == second:
        return not path and first_hash == second_hash
    if not 0 < first < second or not path:
        return False
    path = list(path)
    if first & (first - 1) == 0:  # exact power of two: the old root is itself a node of the new tree
        path = [first_hash] + path
    fn, sn = first - 1, second - 1
    while fn & 1:
        fn, sn = fn >> 1, sn >> 1
    fr = sr = path[0]
    for c in path[1:]:
        if sn == 0:
            return False
        if fn & 1 or fn == sn:
            fr, sr = node_hash(c, fr), node_hash(c, sr)
            if not fn & 1:
                while fn and not fn & 1:
                    fn, sn = fn >> 1, sn >> 1
        else:
            sr = node_hash(sr, c)
        fn, sn = fn >> 1, sn >> 1
    return fr == first_hash and sr == second_hash and sn == 0
