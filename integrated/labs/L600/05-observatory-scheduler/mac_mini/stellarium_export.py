"""Experiment 2b: Stellarium (GPL-2.0) shows - and measures - tonight's plan.

Writes a Stellarium script (.ssc, run with F12 -> Script console -> Load -> Run) that sets the Gurgaon site, freezes
time, and for every block of the optimised plan every 10 minutes sets the UTC date, centres the target and writes
"name,utc,altitude-geometric,altitude" with core.output (Stellarium's output.txt in its user data folder). Then
--compare reads that output.txt and compares Stellarium's geometric altitude (no refraction, like ours) with
sky.alt_deg - a visual check that also produces numbers.

python stellarium_export.py --here                 print the script (no Stellarium needed)
python stellarium_export.py --out plan.ssc         write it; run in Stellarium; then
python stellarium_export.py --compare "$HOME/Library/Application Support/Stellarium/output.txt"
"""
import argparse
import json
import sys
from datetime import datetime

import _lab
import astropy_check
import sky
from timeutil import UtcInstant

ELEV_M = 217


def ssc(rows):
    samples = [(row["target"], t.dt.strftime("%Y-%m-%dT%H:%M:%S")) for row in rows for t in astropy_check.samples(row)]
    lines = ["// Generated by L600 #05 mac_mini/stellarium_export.py - the optimised plan, block starts to ends, UTC.",
             f'core.setObserverLocation({sky.SITE["lon_deg"]}, {sky.SITE["lat_deg"]}, {ELEV_M}, 0, "Gurgaon (kb L600 #05)");',
             "core.setTimeRate(0);", "core.resetOutput();", 'core.output("name,utc,altitude-geometric,altitude");',
             "var plan = " + json.dumps(samples) + ";",
             "for (var i = 0; i < plan.length; i++) {",
             '  core.setDate(plan[i][1], "utc");',
             "  core.selectObjectByName(plan[i][0], true);",
             "  core.moveToSelectedObject(0);",
             "  var m = core.getObjectInfo(plan[i][0]);",
             '  core.output(plan[i][0] + "," + plan[i][1] + "," + m["altitude-geometric"] + "," + m["altitude"]);',
             "  core.wait(0.3);", "}", 'core.output("done");']
    return "\n".join(lines) + "\n"


def compare(text, reqs):
    by, diffs = {r.name: r for r in reqs}, []
    for line in text.splitlines():
        parts = line.strip().split(",")
        if len(parts) != 4 or parts[0] not in by:
            continue
        t = UtcInstant(datetime.fromisoformat(parts[1] + "+00:00"))  # the script wrote these with core.setDate(..., "utc")
        ours = sky.alt_deg(by[parts[0]], t)
        diffs.append({"target": parts[0], "utc": parts[1], "ours": round(ours, 4), "stellarium_geometric": float(parts[2]),
                      "stellarium_apparent": float(parts[3]), "dalt": round(float(parts[2]) - ours, 4)})
    if not diffs:
        return {"samples": 0, "error": "no 'name,utc,alt,alt' lines found - did the script run to 'done'?"}
    worst = max(diffs, key=lambda d: abs(d["dalt"]))
    refr = max(d["stellarium_apparent"] - d["stellarium_geometric"] for d in diffs)
    return {"samples": len(diffs), "max_abs_dalt_deg": abs(worst["dalt"]), "worst": worst,
            "max_refraction_deg": round(refr, 4)}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--here", action="store_true")
    ap.add_argument("--out")
    ap.add_argument("--compare", help="Stellarium output.txt to compare with sky.py")
    a = ap.parse_args(argv)
    r = _lab.build()
    if a.compare:
        from pathlib import Path
        res = compare(Path(a.compare).read_text(encoding="utf-8", errors="replace"), r["reqs"])
        print(json.dumps(res))
        _lab.write_jsonl(_lab.runs_dir(None) / "05-stellarium-compare.jsonl", [res])
        return 0 if res["samples"] else 1
    text = ssc(r["local_rows"])
    if a.out:
        from pathlib import Path
        p = Path(a.out)
        p.unlink(missing_ok=True)
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p}")
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
