"""Experiment 1 - run the fleet node firmware in the official MicroPython micro:bit V2 simulator (two boards).

python mac_mini/make_sim_programs.py --here   write the programs to mac_mini/sim_out/ AND run them on the microbit
                                              topic's CPython stub (two boards, one radio) - what the browser must match
Then on the Mac mini (needs internet for the simulator page; Node 24 + Playwright, as microbit/harness/README.md):
  cd mac_mini/sim && npm install && npx playwright install chromium && npx playwright test

Programs (all generated from firmware/node.py with fleet_sim.patch: each edit must match exactly once):
  node_sim.py           the firmware unchanged except main(): 30 samples 200 ms apart (sleep, not deep_sleep), a final
                        sync, then one serial line "stats sampled=.. frames=.. tries=.. acked=.. left=.. maxframe=.."
  node_sim_wait500.py   same with ACK_WAIT_MS = 500 (ADR 0003's 50 ms is an assumption about a real radio; the browser
                        bridge between two simulator iframes may be slower - this variant separates code from timing)
  node_sim_oversize.py  the failure-lab fault oversize-frame: 27 records per frame with radio length 32
  gateway_sim.py        a minimal device-side gateway for the simulator only (NOT gateway.py): acks the highest
                        contiguous seq per (device, boot) in the firmware's ack format
"""
import argparse
import json
import sys

import _mac
import fleet_sim

OUT = _mac.HERE / "sim_out"
TICKS, GAP_MS = 30, 200

MAIN_OLD = '''def main(dev=1):
    import power
    state = new_state(dev, {})           # on a board: load the flash dict from a file
    while True:
        tick(state)
        power.deep_sleep(ms=SAMPLE_MS)
'''
MAIN_NEW = '''def main(dev=1, ticks=%d, gap_ms=%d):
    # SIMULATOR DRIVER (generated by mac_mini/make_sim_programs.py): sleep instead of deep_sleep, fixed tick count
    state = new_state(dev, {})
    print("node ready schema %%d" %% SCHEMA)
    big = 0
    for _ in range(ticks):
        for f in frames(state):
            big = max(big, len(f))       # largest frame the firmware builds (before the radio truncates it)
        tick(state)
        sleep(gap_ms)
    sync(state)
    s = state["stats"]
    print("stats sampled=%%d frames=%%d tries=%%d acked=%%d left=%%d maxframe=%%d" %% (
        s["sampled"], s["frames"], s["tries"], s["acked"], len(state["flash"]["log"]), big))
''' % (TICKS, GAP_MS)

GATEWAY = '''# Minimal simulator gateway for L600 #04 (generated by mac_mini/make_sim_programs.py; not gateway.py).
# Receives 'D' frames, acks [schema, 'A', dev, epoch(4), n] + n x (boot, hw(2)) = highest contiguous seq per boot.
from microbit import *
import radio

EPOCH = 1790000000
seen = {}
hw = {}


def step():
    f = radio.receive_bytes()
    if f is None or len(f) < 3 or f[1] != ord("D"):
        return f is not None
    schema, dev = f[0], f[2]
    rl = 9 if schema >= 2 else 8
    for i in range(3, len(f) - rl + 1, rl):
        boot, seq = f[i], (f[i + 1] << 8) | f[i + 2]
        s = seen.setdefault((dev, boot), set())
        s.add(seq)
        h = hw.get((dev, boot), 0)
        while h + 1 in s:
            h += 1
        hw[(dev, boot)] = h
    boots = [(b, h) for (d, b), h in hw.items() if d == dev]
    e = EPOCH + running_time() // 1000
    ack = bytes([schema, ord("A"), dev, (e >> 24) & 255, (e >> 16) & 255, (e >> 8) & 255, e & 255, len(boots)])
    for b, h in boots:
        ack += bytes([b, (h >> 8) & 255, h & 255])
    radio.send_bytes(ack)
    print("rx dev=%d len=%d hw=%d" % (dev, len(f), max(h for _, h in boots) if boots else 0))
    return True


def main():
    radio.on()
    radio.config(length=32, queue=16)
    print("gateway ready")
    while True:
        if not step():
            sleep(5)


if __name__ == "__main__":
    main()
'''


def programs():
    src = (fleet_sim.FIRMWARE / "node.py").read_text(encoding="utf-8")
    node = fleet_sim.patch(src, MAIN_OLD, MAIN_NEW)
    return {"node_sim.py": node,
            "node_sim_wait500.py": fleet_sim.patch(node, "ACK_WAIT_MS = 50 ", "ACK_WAIT_MS = 500 "),
            "node_sim_oversize.py": fleet_sim.patch(node, "RECORDS_PER_FRAME = 3 ", "RECORDS_PER_FRAME = 27 "),
            "gateway_sim.py": GATEWAY}


def write(progs):
    OUT.mkdir(exist_ok=True)
    for name, text in progs.items():
        p = OUT / name
        if p.exists():
            p.unlink()   # delete-then-write (the storage mount breaks in-place overwrite)
        p.write_text(text, encoding="utf-8")


class SyncAir:
    """Factory for a stub Air whose gateway answers as soon as a node frame lands (like gateway.FleetAir)."""

    @staticmethod
    def make():
        radio = fleet_sim._kb.radio()

        class Air(radio.Air):
            gateway = None

            def broadcast(self, sender, payload):
                super().broadcast(sender, payload)
                if self.gateway is not None and sender.name != "gw":
                    while self.gateway.lab.step():
                        pass
        return Air()


def run_on_stub(progs, node_file):
    """Both programs on the CPython stub: the gateway's step() and the node's main() as the browser would run them."""
    lt = fleet_sim._kb.labtest()
    air = SyncAir.make()
    boards = lt.load_boards(str(fleet_sim.FIRMWARE), ["gw", "n1"], filename="node.py", air=air,
                            sources={"gw": progs["gateway_sim.py"], "n1": progs[node_file]})
    gw, node = boards
    gw.radio.on()
    gw.radio.config(length=32, queue=16)
    air.gateway = gw
    with lt.serial() as buf:
        node.lab.main()
    line = next(x for x in buf.getvalue().splitlines() if x.startswith("stats"))
    stats = dict(kv.split("=") for kv in line.split()[1:])
    sent = [len(p) for s, _, p in air.log if s == "n1"]
    return {"program": node_file, **{k: int(v) for k, v in stats.items()}, "max_bytes_on_air": max(sent)}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--here", action="store_true", help="also run the programs on the CPython stub")
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    progs = programs()
    write(progs)
    _mac.emit({"written": sorted(progs), "folder": str(OUT.relative_to(_mac.LAB))}, a.out)
    if a.here:
        ok = True
        for f in ("node_sim.py", "node_sim_wait500.py", "node_sim_oversize.py"):
            r = run_on_stub(progs, f)
            over = f == "node_sim_oversize.py"
            r["expect"] = "maxframe > 32, truncated to 32 B on air" if over else "acked=30 left=0, frames <= 32 B"
            ok &= (r["maxframe"] > 32 and r["max_bytes_on_air"] == 32) if over else (
                r["acked"] == TICKS and r["left"] == 0 and r["maxframe"] <= 32)
            _mac.emit({"stub_run": json.loads(json.dumps(r))}, a.out)
        _mac.emit({"stub": "CPython stub (microbit/labs/sim_stub), not MicroPython, not the simulator", "pass": ok}, a.out)
        return 0 if ok else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
