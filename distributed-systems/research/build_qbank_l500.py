def rotate(items, prefix, level, lesson_of):
    out = []
    for i, item in enumerate(items):
        if lesson_of is None:
            lesson, qtype, diff, question, code, opts, expl, src = item
        else:
            qtype, diff, question, code, opts, expl, src = item
            lesson = lesson_of
        pos = i % 4
        others = opts[1:]
        options = others[:pos] + [opts[0]] + others[pos:]
        q = {"id": f"{prefix}{i + 1:03d}" if lesson_of is None else f"{prefix}{i + 1:02d}", "level": level, "lesson": lesson,
             "type": qtype, "difficulty": diff, "question": question}
        if code:
            q["code"] = code
        q.update({"options": options, "answer": pos, "explanation": expl, "source": src})
        out.append(q)
    return out


def write(path, data):
    if path.exists():
        path.unlink()
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


