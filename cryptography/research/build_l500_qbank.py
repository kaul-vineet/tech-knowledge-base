def balanced_positions(n: int, seed: int) -> list[int]:
    base = [i % 4 for i in range(n)]
    random.Random(seed).shuffle(base)
    return base


def build(items, level_id, seed, lesson_fixed=None):
    pos = balanced_positions(len(items), seed)
    out = []
    for i, (item, p) in enumerate(zip(items, pos), 1):
        if lesson_fixed is None:
            lesson, typ, diff, question, code, correct, wrong, expl, src = item
        else:
            typ, diff, question, correct, wrong, expl, src = item
            lesson, code = lesson_fixed, ""
        opts = list(wrong)
        opts.insert(p, correct)
        q = {"id": f"{level_id}-{i:03d}" if lesson_fixed is None else f"{level_id}-{i:02d}", "level": "L500",
             "lesson": lesson, "type": typ, "difficulty": diff, "question": question}
        if code:
            q["code"] = code
        q |= {"options": opts, "answer": p, "explanation": expl, "source": src}
        out.append(q)
    return out


def write(path: Path, data) -> None:
    if path.exists():
        path.unlink()
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


